package com.shadowspark.morontomornica.i18n

enum class AppLanguage(val code: String, val label: String, val nativeName: String) {
  EN("en", "English", "English"),
  PCM("pcm", "Pidgin", "Naija Pidgin"),
  YO("yo", "Yoruba", "Yorùbá"),
  IG("ig", "Igbo", "Igbo"),
  HA("ha", "Hausa", "Hausa"),
  ;

  companion object {
    fun fromCode(code: String?): AppLanguage =
      entries.find { it.code == code } ?: EN
  }
}

